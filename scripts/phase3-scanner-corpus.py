PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
ROUTE = "/api/tools/pdf-scanner"


def label(path: Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def validate_base_url(value: str) -> str:
    parsed = urllib.parse.urlsplit(value)
    if (parsed.scheme != "http" or parsed.hostname not in {"127.0.0.1", "localhost", "::1"}
            or parsed.username or parsed.password or parsed.path not in {"", "/"}
            or parsed.query or parsed.fragment):
        raise ValueError("Only a loopback HTTP origin without credentials is allowed")
    _ = parsed.port
    return value.rstrip("/")


class RejectRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise ValueError(f"Redirect rejected (HTTP {code})")


class LocalTransport:
    def __init__(self, base: str):
        self.base = validate_base_url(base)
        self.opener = urllib.request.build_opener(
            urllib.request.ProxyHandler({}),
            urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()),
            RejectRedirects(),
        )

    def post(self, files: list[dict], filter_value: str) -> tuple[int, bytes, dict, float]:
        boundary = "onlymypdf-scanner-" + uuid.uuid4().hex
        fields = []
        for file in files:
            # Filenames are controlled literals generated by this runner.
            fields.append((f'--{boundary}\r\nContent-Disposition: form-data; name="files"; '
                           f'filename="{file["path"].name}"\r\nContent-Type: {file["mime"]}\r\n\r\n')
                          .encode("ascii") + file["path"].read_bytes() + b"\r\n")
        fields.append((f'--{boundary}\r\nContent-Disposition: form-data; name="filter"\r\n\r\n'
                       f'{filter_value}\r\n--{boundary}--\r\n').encode("ascii"))
        payload = b"".join(fields)
        request = urllib.request.Request(self.base + ROUTE, data=payload, method="POST", headers={
            "Origin": self.base,
            "Content-Type": f"multipart/form-data; boundary={boundary}",
            "User-Agent": "OnlyMyPDF-local-scanner-corpus/1",
        })
        start = time.monotonic()
        try:
            response = self.opener.open(request, timeout=60)
        except urllib.error.HTTPError as error:
            response = error
        with response:
            body = response.read(20 * 1024 * 1024 + 1)
            if len(body) > 20 * 1024 * 1024:
                raise ValueError("Scanner response exceeds 20 MiB diagnostic limit")
            return response.code, body, {k.lower(): v for k, v in response.headers.items()}, time.monotonic() - start


