def write_source(directory: Path, name: str, image: Image.Image, format_name: str,
                 exif_orientation: int | None = None) -> dict:
    extensions = {"PNG": "png", "JPEG": "jpg", "WEBP": "webp"}
    mime = {"PNG": "image/png", "JPEG": "image/jpeg", "WEBP": "image/webp"}[format_name]
    target = directory / f"{name}.{extensions[format_name]}"
    save_options = {"JPEG": {"quality": 96, "subsampling": 0}, "WEBP": {"lossless": True}, "PNG": {}}[format_name]
    if exif_orientation is not None:
        exif = Image.Exif()
        exif[274] = exif_orientation
        save_options = {**save_options, "exif": exif.tobytes()}
    image.save(target, format_name, **save_options)
    with Image.open(target) as reopened:
        stored_size = reopened.size
        actual_orientation = reopened.getexif().get(274, 1)
        expected = ImageOps.exif_transpose(reopened).convert("RGB")
    preview = directory / f"{name}-expected-upright.png"
    expected.save(preview)
    return {"path": target, "mime": mime, "format": format_name, "expected": expected,
            "source": {"path": label(target), "sha256": sha256(target.read_bytes()),
                       "format": format_name, "storedPixels": list(stored_size),
                       "orientation": actual_orientation, "expectedPixels": list(expected.size),
                       "expectedDecodedPixelSha256": sha256(expected.tobytes()), "previewPath": label(preview)}}


