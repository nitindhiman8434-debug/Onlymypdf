def validate_pixels(actual: Image.Image, expected: Image.Image, check: str, format_name: str) -> dict:
    assert actual.size == expected.size, f"Embedded dimensions {actual.size} != oriented source {expected.size}"
    pixels = np.asarray(actual.convert("RGB"), dtype=np.int16)
    reference = np.asarray(expected.convert("RGB"), dtype=np.int16)
    if check == "bw":
        assert np.array_equal(reference[:, :, 0], reference[:, :, 1])
        assert np.array_equal(reference[:, :, 1], reference[:, :, 2])
        binary = np.where(reference >= 128, 255, 0)
        unequal = int(np.count_nonzero(pixels != binary))
        levels = np.unique(pixels).tolist()
        assert levels == [0, 255], f"B&W pixels are not binary: {levels[:16]}"
        assert unequal == 0, f"B&W threshold differs from literal grayscale source in {unequal} channels"
        return {"passed": True, "method": "Exact threshold of independent grayscale source pixels", "threshold": 128,
                "pixelLevels": levels, "differentChannels": unequal}
    difference = np.abs(pixels - reference)
    if check == "enhanced":
        before_range = float(np.percentile(reference[:, :, 0], 95) - np.percentile(reference[:, :, 0], 5))
        after_range = float(np.percentile(pixels[:, :, 0], 95) - np.percentile(pixels[:, :, 0], 5))
        mean_difference = float(difference.mean())
        assert mean_difference > 10, f"Enhanced unchanged or negligible change: {mean_difference}"
        assert after_range >= before_range * 1.5, f"Expected greater measured contrast: {before_range} -> {after_range}"
        # Test broad literal patches away from edges, not Sharp's implementation.
        patch_means = [float(pixels[y + 10:y + 28, 60:570].mean()) for y in [185, 315, 445, 575]]
        assert all(a < b for a, b in zip(patch_means, patch_means[1:])), "Enhanced reversed the ordered gray patches"
        return {"passed": True, "method": "Low-contrast fixture changed and retained ordered gray patches",
                "meanAbsoluteChannelDifference": mean_difference, "sourceP95P5Range": before_range,
                "outputP95P5Range": after_range, "orderedPatchMeans": patch_means,
                "limitations": "Demonstrates this filter changed this fixture; does not prove readability on every photo."}
    mean_difference, maximum = float(difference.mean()), int(difference.max())
    if format_name == "JPEG":
        # Pillow/libjpeg and libvips JPEG decoders may round color conversion
        # differently; no lossy output re-encoding is allowed after decoding.
        assert mean_difference <= 1 and maximum <= 8, f"JPEG decoder/orientation mismatch: mean={mean_difference}, max={maximum}"
        tolerance = {"meanAbsoluteChannelDifferenceMax": 1, "singleChannelDifferenceMax": 8,
                     "reason": "Independent Pillow and app JPEG decoder color rounding; fixture uses 4:4:4 sampling."}
    else:
        assert maximum == 0, f"Lossless {format_name} pixels changed: max channel difference {maximum}"
        tolerance = {"singleChannelDifferenceMax": 0}
    return {"passed": True, "method": "Independent Pillow decoded, EXIF-transposed source compared pixelwise",
            "meanAbsoluteChannelDifference": mean_difference, "maximumChannelDifference": maximum,
            "tolerance": tolerance}


def inspect_pdf(body: bytes, case: dict, output: Path) -> dict:
    assert body.startswith(b"%PDF-"), "Missing PDF magic"
    pages = []
    with fitz.open(stream=body, filetype="pdf") as pdf:
        assert not pdf.is_encrypted, "Unexpected encrypted result"
        assert len(pdf) == len(case["files"]), f"Expected {len(case['files'])} pages, got {len(pdf)}"
        for index, page in enumerate(pdf):
            source = case["files"][index]
            assert abs(page.rect.width - 595.28) <= .05 and abs(page.rect.height - 841.89) <= .05, "Unexpected A4 portrait output geometry"
            assert not page.get_text().strip(), "Scanner unexpectedly added selectable text"
            images = page.get_images(full=True)
            assert len(images) == 1, f"Page {index + 1}: expected one image, got {len(images)}"
            xref = images[0][0]
            extracted = pdf.extract_image(xref)
            with Image.open(io.BytesIO(extracted["image"])) as decoded:
                actual = decoded.convert("RGB")
            embedded = output.parent / f"{case['caseId']}-embedded-{index + 1:02d}.png"
            actual.save(embedded)
            check = validate_pixels(actual, source["expected"], case["check"], source["format"])
            rectangles = page.get_image_rects(xref)
            assert len(rectangles) == 1, "Image unexpectedly drawn more than once"
            scale = min((page.rect.width - 40) / actual.width, (page.rect.height - 40) / actual.height, 1)
            w, h = actual.width * scale, actual.height * scale
            expected_rect = [(page.rect.width - w) / 2, (page.rect.height - h) / 2,
                             (page.rect.width + w) / 2, (page.rect.height + h) / 2]
            assert max(abs(a - b) for a, b in zip(rectangles[0], expected_rect)) <= .05, "Image aspect, fit or centering changed"
            pages.append({"page": index + 1, "sourcePath": source["source"]["path"],
                          "widthPoints": page.rect.width, "heightPoints": page.rect.height,
                          "embeddedPixels": list(actual.size), "embeddedPreviewPath": label(embedded),
                          "imageBoundsPoints": list(rectangles[0]), "selectableTextCharacters": 0,
                          "pixelCheck": check, "passed": True})
    return {"passed": True, "pageCount": len(pages), "pages": pages,
            "pageOrderMethod": "Each embedded page is compared to its same-index literal source, including distinct page number and color patches."}


def render_pdf(pdf_path: Path, case_id: str) -> list[str]:
    executable = shutil.which("pdftoppm")
    if not executable:
        raise FileNotFoundError("Local Poppler pdftoppm is required; no download is performed")
    prefix = pdf_path.parent / f"{case_id}-output"
    completed = subprocess.run([executable, "-png", "-r", "96", str(pdf_path), str(prefix)],
                               capture_output=True, text=True, timeout=45)
    if completed.returncode:
        raise RuntimeError(f"Poppler render failed: {completed.stderr[:300]}")
    paths = sorted(pdf_path.parent.glob(f"{case_id}-output-*.png"), key=lambda p: int(p.stem.rsplit("-", 1)[1]))
    return [label(p) for p in paths]


def run_case(transport: LocalTransport, case: dict, destination: Path, negative: bool) -> dict:
    result = {"caseId": case["caseId"], "filter": case["filter"], "inputFiles": len(case["files"]),
              "kind": "negative" if negative else "positive"}
    try:
        status, body, headers, seconds = transport.post(case["files"], case["filter"])
        result.update(httpStatus=status, contentType=headers.get("content-type", ""), outputBytes=len(body),
                      responseSha256=sha256(body), httpSeconds=round(seconds, 3))
        if negative:
            assert status == 400, f"Expected HTTP 400 for invalid input, got {status}"
            assert "application/json" in result["contentType"], "Invalid input did not return JSON"
            assert not body.startswith(b"%PDF-"), "Invalid batch returned partial PDF"
            payload = json.loads(body)
            message = payload.get("error", "")
            assert isinstance(message, str) and case["error"] in message.lower(), f"Unhelpful error: {message}"
            result.update(error=message, noPdfArtifact=True)
        else:
            assert status == 200, f"Expected PDF success, got HTTP {status}: {body[:240]!r}"
            assert result["contentType"].split(";", 1)[0].strip() == "application/pdf", "Wrong PDF MIME"
            assert 'filename="scanned-document.pdf"' in headers.get("content-disposition", ""), "Missing PDF download filename"
            if "content-length" in headers:
                assert int(headers["content-length"]) == len(body), "Response byte count differs from Content-Length"
            output = destination / f"{case['caseId']}-result.pdf"
            output.write_bytes(body)
            result["outputPath"] = label(output)
            result["validation"] = inspect_pdf(body, case, output)
            result["renderedPreviewPaths"] = render_pdf(output, case["caseId"])
            assert len(result["renderedPreviewPaths"]) == len(case["files"]), "Independent renderer page count differs"
        result["status"] = "passed"
    except Exception as error:
        result.update(status="failed", failure=str(error))
    return result


def contact_sheet(results: list[dict], destination: Path) -> str | None:
    previews = [(r["caseId"], p) for r in results for p in r.get("renderedPreviewPaths", [])]
    if not previews:
        return None
    columns, cell_width, cell_height = 4, 245, 380
    sheet = Image.new("RGB", (columns * cell_width, ((len(previews) + columns - 1) // columns) * cell_height), (232, 237, 242))
    draw = ImageDraw.Draw(sheet)
    for index, (name, path) in enumerate(previews):
        with Image.open(ROOT / path) as image:
            image = image.convert("RGB")
            image.thumbnail((cell_width - 14, cell_height - 45))
            x, y = index % columns * cell_width, index // columns * cell_height
            draw.text((x + 7, y + 6), name[:31], fill=(25, 35, 50), font=font(12))
            sheet.paste(image, (x + (cell_width - image.width) // 2, y + 29))
    path = destination / "output-contact-sheet.png"
    sheet.save(path)
    return label(path)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://127.0.0.1:3001")
    parser.add_argument("--run-label", required=True, help="Fresh label; existing reports/artifacts are never overwritten")
    parser.add_argument("--generate-only", action="store_true")
    args = parser.parse_args()
    base = validate_base_url(args.base_url)
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,63}", args.run_label):
        parser.error("Use a lowercase alphanumeric/hyphen run label")
    destination = ARTIFACT_ROOT / args.run_label
    report_path = REPORT_ROOT / f"{args.run_label}-report.json"
    if destination.exists() or report_path.exists():
        parser.error("Run label already exists; choose a fresh label")
    positive, negative = make_fixtures(destination / "sources")
    report = {"schemaVersion": 1, "phase": "3.4", "generatedAt": datetime.now(timezone.utc).isoformat(),
              "runLabel": args.run_label, "baseUrl": base, "generateOnly": args.generate_only,
              "validatorSha256": sha256(Path(__file__).read_bytes()),
              "method": "Actual loopback HTTP; Pillow source and EXIF oracle; MuPDF PDF/image extraction; independent Poppler 96 DPI output renders. No app processing code imported.",
              "limitations": ["Synthetic static JPG/PNG/WebP images only; no real-customer acceptance, handwriting, OCR, animation, automatic crop or perspective-correction claim.",
                              "Enhanced checks measure a deliberate low-contrast fixture, not universal readability or quality improvement.",
                              "JPEG allows independent decoder rounding only (mean channel difference <=1, max<=8); lossless PNG/WebP and grayscale B&W thresholds require exact pixels.",
                              "All source and output previews need separate visual inspection; HTTP timings are individual local observations.",
                              "No cloud requests, paid services, browser actions, source code changes, response redirects or configured HTTP proxies are used."],
              "sources": [{"caseId": c["caseId"], "filter": c["filter"], "check": c["check"],
                           "files": [f["source"] for f in c["files"]]} for c in positive], "results": []}
    if not args.generate_only:
        transport = LocalTransport(base)
        for negative_case, cases in [(False, positive), (True, negative)]:
            for case in cases:
                result = run_case(transport, case, destination, negative_case)
                report["results"].append(result)
                print(json.dumps({"caseId": case["caseId"], "status": result["status"],
                                  "httpStatus": result.get("httpStatus"), "failure": result.get("failure")}), flush=True)
    results = report["results"]
    report["summary"] = {"positiveCases": len(positive), "negativeCases": len(negative),
                         "routesTested": len(results), "passed": sum(r["status"] == "passed" for r in results),
                         "failed": sum(r["status"] != "passed" for r in results),
                         "renderedPages": sum(len(r.get("renderedPreviewPaths", [])) for r in results),
                         "allPassed": len(results) == len(positive) + len(negative) and all(r["status"] == "passed" for r in results)}
    report["outputContactSheet"] = contact_sheet(results, destination)
    REPORT_ROOT.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"report": label(report_path), "summary": report["summary"],
                      "outputContactSheet": report["outputContactSheet"]}), flush=True)
    return 0 if args.generate_only or report["summary"]["allPassed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
